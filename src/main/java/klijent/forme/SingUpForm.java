    private void btnSingUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSingUpActionPerformed
        String firstName = txtFirstName.getText();
        String lastName = txtLastName.getText();
        String email = txtEmail.getText();
        String password = String.valueOf(txtPassword.getPassword());

        String greska = validacija();

        if (!greska.equals("")) {
            JOptionPane.showMessageDialog(this, greska);
            return;
        }

        //Kada svi uneti podaci budu odgovarajuci i prodju validaciju, ja ih pokupim iz forme i lozinku hesujem i takvu dalje prosledjujem
        String hashPassword = PasswordUtill.hesujLozinku(password);

        Users user = new Users(-1, firstName, lastName, email, hashPassword, null, null);

        KlijentskiZahtev kz = new KlijentskiZahtev();
        kz.setOperacija(Operacije.SINGUP);
        kz.setParametar(user);

        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        boolean uspesnoRegistovan = (boolean) so.getOdgovor();

        if (!uspesnoRegistovan) {
            Object[] opcije = {"Try again", "Exit"};
            int izbor = JOptionPane.showOptionDialog(this, "Doslo je do greske prilikom registracije, vec postoji korisnik sa ovom email adresom!", "Information Form", JOptionPane.DEFAULT_OPTION, JOptionPane.INFORMATION_MESSAGE, null, opcije, opcije[1]);
            switch (izbor) {
                case 0:
                    srediFormu();
                    break;
                case 1:
                    this.dispose();
                    break;
                default:
                    return;
            }
            return;
        }
        JOptionPane.showMessageDialog(this, "Registracija uspesno obavljena!");
        SingInForm sif = new SingInForm();
        sif.setVisible(true);
        this.dispose();

    }//GEN-LAST:event_btnSingUpActionPerformed

