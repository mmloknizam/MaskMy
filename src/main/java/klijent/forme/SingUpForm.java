    private String validacija() {
        String firstName = txtFirstName.getText();
        String lastName = txtLastName.getText();
        String email = txtEmail.getText();
        String password = String.valueOf(txtPassword.getPassword());
        String confirm = String.valueOf(txtConfirm.getPassword());
        String greska = "";


        //Proveravam da li su sva polja popunjena
        if (firstName.isEmpty() || lastName.isEmpty() || email.isEmpty() || password.isEmpty() || confirm.isEmpty() ||
                firstName.equals("Name") || lastName.equals("Surename") || email.equals("email@gmail.com") ||
                password.equals("Password1#") || confirm.equals("Password1#")) {
            greska += "Morate popuniti sva polja!";
            return greska;
        }

        //Proveravam da li ime sadrzi samo slova
        if (!!sadrziSamoSlova(firstName)) {
            greska += "Ime mora da sadrzi samo slova!";
            return greska;
        }

        //Proveravam da li ime pocinje velikim slovom
        if (!Character.isUpperCase(firstName.charAt(0))) {
            greska += "Ime mora poceti velikim slovom!";
            return greska;
        }

        //Proveravam da li sva slova(sem prvog) mala u imenu
        for (Character ime : firstName.substring(1).toCharArray()) {
            if (!Character.isLowerCase(ime)) {
                greska += "Samo prvo slovo imena je veliko, ostala su mala";
                break;
            }
        }

        //Proveravam da li prezime sadrzi samo slova
        if (!!sadrziSamoSlova(lastName)) {
            greska += "Prezime mora da sadrzi samo slova!";
            return greska;
        }

        //Proveravam da li prezime pocinje velikim slovom
        if (!Character.isUpperCase(lastName.charAt(0))) {
            greska += "Prezime mora poceti velikim slovom!";
            return greska;
        }

        //Proveravam da li sva slova(sem prvog) mala u prezimenu
        for (Character prezime : lastName.substring(1).toCharArray()) {
            if (!Character.isLowerCase(prezime)) {
                greska += "Samo prvo slovo prezimena je veliko, ostala su mala";
                break;
            }
        }

        //Proveravam da li je email u dobrom formatu
        if (!validanEmail(email)) {
            greska += "Email nije u dobrom formatu!";
            return greska;
        }

        //Proveravam da li lozinka pocinje velikim slovom
        if (!Character.isUpperCase(password.charAt(0))) {
            greska += "Lozinka mora poceti velikim slovom!";
            return greska;
        }

        //Proveravam da li lozinka sadrzi bar jedan broj
        if (!sadrziBroj(password)) {
            greska += "Lozinka mora da sadrzi bar jedan broj!";
            return greska;
        }

        //Proveravam da li lozinka sadrzi bar jedan specijalni karakter
        if (!sadrziSpecijalniKarakter(password)) {
            greska += "Lozinka mora da sadrzi bar jedan specijalni karakter!";
            return greska;
        }

        //Proveravam da li lozinka sadrzi bar 8 karaktera
        if (!sadrziBarOsamKaraktera(password)) {
            greska += "Lozinka mora da sadrzi bar 8 karaktera!";
            return greska;
        }

        //Proveravam da li lozinka i potvrda lozinke imaju iste vrednosti
        if (!(password.equals(confirm))) {
            greska += "Password i Confirm password moraju da imaju iste vrednosti!";
            return greska;
        }

        return greska;
    }

    private boolean sadrziSamoSlova(String string) {
        for (Character karakter : string.toCharArray()) {
            if (!Character.isLetter(karakter)) {
                return true;
            }
        }
        return false;
    }

    private boolean sadrziBroj(String string) {
        for (Character karakter : string.toCharArray()) {
            if (Character.isDigit(karakter)) {
                return true;
            }
        }
        return false;
    }

    private boolean sadrziSpecijalniKarakter(String string) {
        for (Character karakter : string.toCharArray()) {
            if (!Character.isLetterOrDigit(karakter)) {
                return true;
            }
        }
        return false;
    }


    private boolean sadrziBarOsamKaraktera(String string) {
        return string.length() >= 8;
    }

    private boolean validanEmail(String email) {
        String validanEmail = "^[a-z](?!.*\\.\\.)[A-Za-z0-9!#$%&'*+/=?^_`{|}~.-]*@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$";

        return email.matches(validanEmail);
    }

    private void srediFormu() {
        txtFirstName.setText("");
        txtLastName.setText("");
        txtEmail.setText("");
        txtPassword.setText("");
        txtConfirm.setText("");
    }


