    private String validacija() {
        String current = String.valueOf(txtCurrent.getPassword());
        String neew = String.valueOf(txtNew.getPassword());
        String confirm = String.valueOf(txtConfirm.getPassword());
        String greska = "";


        //Proveravam da li su sva polja popunjena
        if (current.isEmpty() || neew.isEmpty() || confirm.isEmpty() ||
                current.equals("Password1#") || neew.equals("Password2#") || confirm.equals("Password2#")) {
            greska += "Morate popuniti sva polja!";
            return greska;
        }

        //Proveravam da li lozinka pocinje velikim slovom
        if (!Character.isUpperCase(neew.charAt(0))) {
            greska += "Lozinka mora poceti velikim slovom!";
            return greska;
        }

        //Proveravam da li lozinka sadrzi bar jedan broj
        if (!sadrziBroj(neew)) {
            greska += "Lozinka mora da sadrzi bar jedan broj!";
            return greska;
        }

        //Proveravam da li lozinka sadrzi bar jedan specijalni karakter
        if (!sadrziSpecijalniKarakter(neew)) {
            greska += "Lozinka mora da sadrzi bar jedan specijalni karakter!";
            return greska;
        }

        if (!sadrziBarOsamKaraktera(neew)) {
            greska += "Lozinka mora da sadrzi bar 8 karaktera!";
            return greska;
        }

        //Proveravam da li lozinka i potvrda lozinke imaju iste vrednosti
        if (!(neew.equals(confirm))) {
            greska += "New password i Confirm password moraju da imaju iste vrednosti!";
            return greska;
        }

        //Proveravam da li su stara i nova lozinka iste 
        if (current.equals(neew)) {
            greska += "New password ne sme biti ista kao Current password!";
            return greska;
        }

        return greska;
    }


    private boolean sadrziBroj(String string) {
        for (Character karakter : string.toCharArray()) {
            if (Character.isDigit(karakter)) {
                return true;
            }
        }
        return false;
    }

    private boolean sadrziSpecijalniKarakter(String string) {
        for (Character karakter : string.toCharArray()) {
            if (!Character.isLetterOrDigit(karakter)) {
                return true;
            }
        }
        return false;
    }


    private boolean sadrziBarOsamKaraktera(String string) {
        return string.length() >= 8;
    }

