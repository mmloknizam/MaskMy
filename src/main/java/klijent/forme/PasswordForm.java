    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        String current = String.valueOf(txtCurrent.getPassword());
        String neew = String.valueOf(txtNew.getPassword());
        String confirm = String.valueOf(txtConfirm.getPassword());

        String greska = validacija();

        if (!greska.equals("")) {
            JOptionPane.showMessageDialog(this, greska);
            return;
        }

        //Prvo moram da proverim da li se Password poklapa sam passwordom iz baze
        Users u = new Users();
        u.setUserID(ulogovani.getUserID());
        u.setPassword(current);

        KlijentskiZahtev kz = new KlijentskiZahtev();
        kz.setOperacija(Operacije.VRATI_PASSWORD);
        kz.setParametar(u);

        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();

        boolean ispravanPassword = (boolean) so.getOdgovor();

        if (!ispravanPassword) {
            Object[] opcije = {"Try again", "Exit"};
            int izbor = JOptionPane.showOptionDialog(this, "Current password je pogresan!", "Information Form", JOptionPane.DEFAULT_OPTION, JOptionPane.INFORMATION_MESSAGE, null, opcije, opcije[1]);
            switch (izbor) {
                case 0:
                    txtCurrent.setText("");
                    txtNew.setText("");
                    txtConfirm.setText("");
                    break;
                case 1:
                    this.dispose();
                    break;
            }
            return;
        }

        //Kada svi uneti podaci budu odgovarajuci i prodju validaciju, ja ih pokupim iz forme i lozinku hesujem i takvu dalje prosledjujem
        String hashNewPassword = PasswordUtill.hesujLozinku(neew);

        Users user = new Users();
        user.setUserID(ulogovani.getUserID());
        user.setPassword(hashNewPassword);

        KlijentskiZahtev kz1 = new KlijentskiZahtev();
        kz1.setOperacija(Operacije.IZMENI_PASSWORD);
        kz1.setParametar(user);

        Komunikacija.getInstance().posaljiZahtev(kz1);
        ServerskiOdgovor so1 = Komunikacija.getInstance().primiOdgovor();

        boolean uspesnoIzmenjenPassword = (boolean) so1.getOdgovor();

        if (!uspesnoIzmenjenPassword) {
            Object[] opcije = {"Try again", "Exit"};
            int izbor = JOptionPane.showOptionDialog(this, "Doslo je do greske prilikom izmene lozinke!", "Information Form", JOptionPane.DEFAULT_OPTION, JOptionPane.INFORMATION_MESSAGE, null, opcije, opcije[1]);
            switch (izbor) {
                case 0:
                    txtCurrent.setText("");
                    txtNew.setText("");
                    txtConfirm.setText("");
                    break;
                case 1:
                    this.dispose();
                    break;
            }
            return;
        }

        JOptionPane.showMessageDialog(this, "Uspesno ste izmenili lozinku!");
        this.dispose();
    }//GEN-LAST:event_btnIzmeniActionPerformed

