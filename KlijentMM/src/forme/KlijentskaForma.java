    private void btnPretraziActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPretraziActionPerformed
         String text=txtPretraga.getText().trim().toLowerCase();
         
         if(text.isEmpty() || text.equals("text...")){
             JOptionPane.showMessageDialog(this, "Morate uneti tekst koji zelite da pretrazite!");
             tblEntries.setModel(new ModelTableEntries(ulogovani, new ArrayList<>()));
             jTree1.clearSelection();
             return;
         }
         
         ArrayList<Entries> rezultat=new ArrayList<>();

         DefaultMutableTreeNode root=(DefaultMutableTreeNode) jTree1.getModel().getRoot();
         
         pretraziStablo(root, text, rezultat);
         
         if(rezultat.isEmpty()){
             JOptionPane.showMessageDialog(this, "Nema rezultata za: "+text);
             tblEntries.setModel(new ModelTableEntries(ulogovani, new ArrayList<>()));
             return;
         }
         
         tblEntries.setModel(new ModelTableEntries(ulogovani,rezultat));
         
    }//GEN-LAST:event_btnPretraziActionPerformed

