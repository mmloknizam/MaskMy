    private void popuniStablo() {
        //prvo vracam sve grupe za korisnika
        KlijentskiZahtev kz=new KlijentskiZahtev();
        kz.setOperacija(Operacije.VRATI_GRUPE);
        kz.setParametar(ulogovani);
        
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();
        
        ArrayList<Groups> grupe=(ArrayList<Groups>) so.getOdgovor();
        
        DefaultTreeModel model=(DefaultTreeModel) jTree1.getModel();
        DefaultMutableTreeNode root=(DefaultMutableTreeNode) model.getRoot();
        
        root.removeAllChildren();
        
        for(Groups g: grupe){
            DefaultMutableTreeNode cvor=new DefaultMutableTreeNode(g, true);
            
            //Za svaku grupu koja ima entry dodajem ga
            KlijentskiZahtev kz2=new KlijentskiZahtev();
            kz2.setOperacija(Operacije.VRATI_ENTRIJE_ZA_GRUPU);
            kz2.setParametar(new ZahtevZaEntrije(g, ulogovani));
            
            Komunikacija.getInstance().posaljiZahtev(kz2);
            ServerskiOdgovor so2=Komunikacija.getInstance().primiOdgovor();
            
            ArrayList<Entries> entriesG=(ArrayList<Entries>) so2.getOdgovor();
            
            for(Entries e: entriesG){
                DefaultMutableTreeNode list=new DefaultMutableTreeNode(e, false);
                cvor.add(list);
            }        
            root.add(cvor);
        }
        
        KlijentskiZahtev kz3=new KlijentskiZahtev();
        kz3.setOperacija(Operacije.VRATI_ENTRIJE_BEZ_GRUPA);
        kz3.setParametar(ulogovani);
        
        Komunikacija.getInstance().posaljiZahtev(kz3);
        ServerskiOdgovor so3=Komunikacija.getInstance().primiOdgovor();
        
        ArrayList<Entries> entries=(ArrayList<Entries>) so3.getOdgovor();
        
        for(Entries e: entries){
                DefaultMutableTreeNode list=new DefaultMutableTreeNode(e, false);
                root.add(list);
        }
                
        model.reload();
    }

    
    private void  pretraziStablo(DefaultMutableTreeNode root, String text, ArrayList<Entries> rezultat){
        if(root==null){
            return;
        }
        
        Object obj=root.getUserObject();
        
        if(obj instanceof Entries entry){
            String lower=text.toLowerCase();
            if(text.isEmpty()||
               entry.getTitle().toLowerCase().contains(lower) ||
               entry.getUsername().toLowerCase().contains(lower) ||
               entry.getUrl().toLowerCase().contains(lower) ||
               entry.getNote().toLowerCase().contains(lower)){
                 rezultat.add(entry);
            }
        }
        
        Enumeration<?> children=root.children();
        while(children.hasMoreElements()){
            DefaultMutableTreeNode child=(DefaultMutableTreeNode) children.nextElement(); 
            pretraziStablo(child, text, rezultat);
        }
    
    }
