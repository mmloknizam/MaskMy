    private void btnSingOutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSingOutActionPerformed
        int result=JOptionPane.showConfirmDialog(this, "Da li ste sigurni da zelite da se odjavite?", "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if(result==JOptionPane.NO_OPTION){
            return;
        }

        if(result==JOptionPane.YES_OPTION){
            KlijentskiZahtev kz=new KlijentskiZahtev();
            kz.setOperacija(Operacije.SINGOUT);
            kz.setParametar(ulogovani.getUserID());

            Komunikacija.getInstance().posaljiZahtev(kz);
            ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();

            boolean uspesnoOdjavljen=(boolean) so.getOdgovor();

            if(uspesnoOdjavljen){
                JOptionPane.showMessageDialog(this, "Uspesno ste se odjavili sa sistema!");
                System.exit(0);
            } else{
                JOptionPane.showMessageDialog(this, "Doslo je do greske prilikom odjve...");
            }

        }
    }//GEN-LAST:event_btnSingOutActionPerformed

    private void jTree1ValueChanged(javax.swing.event.TreeSelectionEvent evt) {//GEN-FIRST:event_jTree1ValueChanged
        DefaultMutableTreeNode listCvor=(DefaultMutableTreeNode) jTree1.getLastSelectedPathComponent();

        if(listCvor==null){
            return;
        }

        Object obj=listCvor.getUserObject();
        ModelTableEntries mt=(ModelTableEntries) tblEntries.getModel();

        if(obj instanceof Entries selektovanEntry){
            mt.prikaziSelektovanEntry(selektovanEntry);
        }else if(obj instanceof Groups selektovanaGrupa){
            mt.prikaziEntrijeZaGrupu(selektovanaGrupa);
        } else{
            mt.ocistiTabelu();
        }
    }//GEN-LAST:event_jTree1ValueChanged

    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        DefaultMutableTreeNode listCvor=(DefaultMutableTreeNode) jTree1.getLastSelectedPathComponent();

        if(listCvor==null){
            JOptionPane.showMessageDialog(this, "Morate selektovati ono sto zelite da obrisete!");
            return;
        }

        int rezultat=JOptionPane.showConfirmDialog(this,"Da li ste sigurni da zelite da obrisete unos/grupu?", "Konfirmacija", JOptionPane.YES_NO_OPTION);
        if(rezultat==JOptionPane.NO_OPTION){
            return;
        }

        Object obj=listCvor.getUserObject();
        ModelTableEntries mt=(ModelTableEntries) tblEntries.getModel();

        if(obj instanceof Entries selektovanEntry){
            KlijentskiZahtev kz=new KlijentskiZahtev();
            kz.setOperacija(Operacije.OBRISI_ENTRY);
            kz.setParametar(selektovanEntry);

            Komunikacija.getInstance().posaljiZahtev(kz);
            ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();

            boolean uspesnoObrisanEntry=(boolean) so.getOdgovor();

            if(!uspesnoObrisanEntry){
                JOptionPane.showMessageDialog(this, "Doslo je do greske prilikom brisanja!");
                return;
            }

            JOptionPane.showMessageDialog(this, "Uspesno ste obrisali unos!");
            SwingUtilities.invokeLater(()->{
                popuniStablo();
                mt.ocistiTabelu();
            });

        }
        if(obj instanceof Groups selektovanaGrupa){
            KlijentskiZahtev kz=new KlijentskiZahtev();
            kz.setOperacija(Operacije.OBRISI_GRUPU);
            kz.setParametar(new ZahtevZaEntrije(selektovanaGrupa, ulogovani));

            Komunikacija.getInstance().posaljiZahtev(kz);
            ServerskiOdgovor so=Komunikacija.getInstance().primiOdgovor();

            boolean uspesnoObrisanaGrupa=(boolean) so.getOdgovor();

            if(!uspesnoObrisanaGrupa){
                JOptionPane.showMessageDialog(this, "Doslo je do greske prilikom brisanja!");
                return;
            }

            JOptionPane.showMessageDialog(this, "Uspesno ste obrisali unos!");
            SwingUtilities.invokeLater(()->{
                popuniStablo();
                mt.ocistiTabelu();
            });
        }
    }//GEN-LAST:event_btnObrisiActionPerformed

